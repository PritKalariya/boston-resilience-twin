"""Write Data-Pipeline/dvc.yaml from pipeline_steps.step_plan (#18, ADR-024).

Each stage runs one daily_pipeline step of the full build as
`python scripts/pipeline_steps.py <step>`, the run_step the DAG task calls, so
a step's script, arguments and files are defined once, in step_plan. Its deps
are the files step_plan reads and the code that runs (pipeline_steps.py, the
step's script and the pipeline scripts it imports at module level); its outs
are the files and folders step_plan says it writes. Downloads, the statistics
history and the 311 downloads (keep_outputs) are persist outs: DVC keeps them
when the stage runs again, as the DAG does. The DAG's per-year legacy parse is
one stage per year, then merge_legacy_311, as in the DAG.

STEPS lists the steps in DAG order and LEFT_OUT the ones that are not stages,
with the reason. The schedule state in Data-Pipeline/data/state/ is not an out:
it records what this machine fetched when, and it is not data.

The paths are relative to Data-Pipeline/, where `dvc repro` runs. A test fails
when the committed dvc.yaml differs from what this script writes, so after a
change to step_plan run:

    python Data-Pipeline/scripts/dvc_stages.py           # write dvc.yaml
    python Data-Pipeline/scripts/dvc_stages.py --check   # exit 1 if dvc.yaml is stale
"""

from __future__ import annotations

import argparse
import ast
import json
import os
import re
import sys
from pathlib import Path

import pipeline_steps as steps

PIPELINE = steps.REPO / "Data-Pipeline"
SCRIPTS_DIR = PIPELINE / "scripts"
DVC_YAML = PIPELINE / "dvc.yaml"

# The DAG's real steps that are dvc.yaml stages, in DAG order. parse_legacy_311
# becomes one stage per legacy year.
STEPS = [
    "ingest_legacy_311",
    "ingest_new_311",
    "ingest_noaa_logan",
    "ingest_tides",
    "ingest_open_meteo",
    "ingest_static_layers",
    "ingest_alert_history",
    "validate_raw",
    "parse_legacy_311",
    "merge_legacy_311",
    "parse_new_311",
    "combine_311",
    "spatial_join",
    "daily_counts",
    "surge_labels",
    "feature_table",
    "validate_processed",
    "schema_and_statistics",
    "bias_slicing",
]
LEFT_OUT = {
    "ingest_nws_forecasts": "a live snapshot of the current forecast: no public source rebuilds past ones, and no stage reads them",
    "ingest_nws_alerts": "a live snapshot of the active alerts: no public source rebuilds past ones, and no stage reads them "
                         "(the alert history comes from ingest_alert_history, ADR-014)",
}
HEADER = """\
# Generated by Data-Pipeline/scripts/dvc_stages.py from pipeline_steps.step_plan
# (#18, ADR-024). Do not edit: change step_plan, then run
#   python Data-Pipeline/scripts/dvc_stages.py
# Run from Data-Pipeline/: `dvc pull && dvc repro`, or `dvc repro` alone to
# rebuild from the public sources (runbook, "Versioned data (DVC)").
"""
PLAIN = re.compile(r"[A-Za-z0-9_./][A-Za-z0-9_./ -]*")


def script_modules(module: str) -> list[str]:
    """module and the pipeline scripts it imports at module level, recursively, sorted.
    Imports inside a function (pandas, or legacy_311 for row counts) are left out."""
    seen: set[str] = set()
    todo = [module]
    while todo:
        name = todo.pop()
        if name in seen:
            continue
        seen.add(name)
        tree = ast.parse((SCRIPTS_DIR / f"{name}.py").read_text(encoding="utf-8"))
        for node in tree.body:
            if isinstance(node, ast.Import):
                found = [alias.name for alias in node.names]
            elif isinstance(node, ast.ImportFrom) and node.level == 0 and node.module:
                found = [node.module]
            else:
                continue
            todo += [name for name in found if (SCRIPTS_DIR / f"{name}.py").is_file()]
    return sorted(seen)


def relative(path: Path) -> str:
    """A path as dvc.yaml writes it: relative to Data-Pipeline/, with forward slashes."""
    return Path(os.path.relpath(path, PIPELINE)).as_posix()


def inside(path: Path, folder: Path) -> bool:
    """Whether path is folder or lies under it."""
    return path == folder or folder in path.parents


def stage(step: str, year: int | None = None) -> dict:
    """One dvc.yaml stage: {"cmd": ..., "deps": [...], "outs": [(path, persist), ...]}."""
    plan = steps.step_plan(step, steps.DateRange(), year=year)
    modules = script_modules("pipeline_steps")
    if step in steps.SCRIPTS:
        modules = sorted({*modules, *script_modules(steps.SCRIPTS[step])})
    code = [SCRIPTS_DIR / f"{name}.py" for name in modules]
    folders = [*plan.keeps, *plan.writes_too]
    outs = [*folders, *(path for path in plan.files.data_out if not any(inside(path, f) for f in folders))]
    persisted = set(plan.keeps) | (set(outs) if plan.keep_outputs else set())
    cmd = f"python scripts/pipeline_steps.py {step}" + (f" --year {year}" if year is not None else "")
    return {
        "cmd": cmd,
        "deps": list(dict.fromkeys(relative(path) for path in [*code, *plan.files.data_in, *plan.files.config_in])),
        "outs": [(relative(path), path in persisted) for path in outs],
    }


def stages() -> dict[str, dict]:
    """Every stage by name, in STEPS order."""
    out = {}
    for step in STEPS:
        if step == "parse_legacy_311":
            for year in steps.LEGACY_YEARS:
                out[f"{step}_{year}"] = stage(step, year)
        else:
            out[step] = stage(step)
    return out


def scalar(value: str) -> str:
    """A YAML string: plain when it is a simple path or command, else double-quoted (JSON is valid YAML)."""
    return value if PLAIN.fullmatch(value) and not value.endswith(" ") else json.dumps(value)


def render() -> str:
    """The text of dvc.yaml."""
    lines = [HEADER.rstrip("\n"), "stages:"]
    for name, spec in stages().items():
        lines += [f"  {name}:", f"    cmd: {scalar(spec['cmd'])}"]
        if spec["deps"]:
            lines += ["    deps:", *(f"    - {scalar(dep)}" for dep in spec["deps"])]
        if spec["outs"]:
            lines.append("    outs:")
            for path, persist in spec["outs"]:
                lines += [f"    - {scalar(path)}:", "        persist: true"] if persist else [f"    - {scalar(path)}"]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> None:
    """Write dvc.yaml, or with --check exit 1 when the committed one is stale."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="only compare; exit 1 if dvc.yaml differs")
    args = parser.parse_args(argv)
    text = render()
    current = DVC_YAML.read_text(encoding="utf-8") if DVC_YAML.is_file() else ""
    if args.check:
        if current != text:
            sys.exit(f"{DVC_YAML} is stale: run python Data-Pipeline/scripts/dvc_stages.py")
        print(f"{DVC_YAML} is current ({len(stages())} stages)")
        return
    if current == text:
        print(f"{DVC_YAML} unchanged ({len(stages())} stages)")
        return
    DVC_YAML.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {DVC_YAML} ({len(stages())} stages)")


if __name__ == "__main__":
    main()
